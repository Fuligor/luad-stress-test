import os
import argparse
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

# --- CONFIG ---
MODEL_MAPPING = {
    'efficientnet-base': 'EfficientNet',
    'gigapath-base': 'GigaPath',
    'resnet-base': 'ResNet',
    'swin-base': 'Swin Transformer',
    'uni-base': 'UNI',
    'virchow2-base': 'Virchow2',
    'vit-base': 'ViT'
}

GROUPS = {
    'CNN-based': {'models': ['ResNet', 'EfficientNet'], 'colors': ['#1f77b4', '#00bfff']},
    'Transformer-based': {'models': ['ViT', 'Swin Transformer'], 'colors': ['#ff7f0e', '#d62728']},
    'PFM': {'models': ['GigaPath', 'UNI', 'Virchow2'], 'colors': ['#2ca02c', '#9467bd', '#8c564b']}
}

DATASETS_TO_PLOT = ['GLOBAL', 'TCGA', 'ANORAK']

def main(input_csv, output_dir):
    # Ensure output directory exists
    os.makedirs(output_dir, exist_ok=True)

    # 1. Data Preparation
    # Load the table generated by the bootstrap script
    df = pd.read_csv(input_csv)

    # Map model names and ensure the Robustness Score is used correctly
    df['Model'] = df['Model'].map(MODEL_MAPPING).fillna(df['Model'])
    df['Robustness_Plot_Value'] = df['Robustness_R'] 

    # 2. Establish common scale
    df_all_target = df[(df['Dataset'].isin(DATASETS_TO_PLOT)) & (df['Artifact'] != 'base')].copy()

    global_min = df_all_target['Robustness_Plot_Value'].min()
    global_max = df_all_target['Robustness_Plot_Value'].max()

    # Margins for readability (e.g., 60% to 105%)
    lower_limit = max(0, int(np.floor(global_min / 10) * 10) - 5)
    upper_limit = int(np.ceil(global_max / 5) * 5)
    if upper_limit < 100: 
        upper_limit = 100 

    print(f"Calculated common scale: {lower_limit}% - {upper_limit}%")

    # 3. Main Loop
    for dataset_name in DATASETS_TO_PLOT:
        print(f"Generating chart for: {dataset_name}...")
        
        df_radar = df[(df['Dataset'] == dataset_name) & (df['Artifact'] != 'base')].copy()
        
        # Pivot: Artifacts become the axes (arms) of the radar
        pivot_df = df_radar.pivot(index='Model', columns='Artifact', values='Robustness_Plot_Value')

        labels = pivot_df.columns.tolist()
        num_vars = len(labels)
        angles = np.linspace(0, 2 * np.pi, num_vars, endpoint=False).tolist()
        angles += angles[:1]

        fig, ax = plt.subplots(figsize=(8, 9), subplot_kw=dict(polar=True))

        # Baseline (100%) - reference point
        baseline_values = [100] * (num_vars + 1)
        ax.plot(angles, baseline_values, color="red", linestyle="--", linewidth=1.2, zorder=10, label="Baseline (100%)")

        # Draw models
        for group_name, group_info in GROUPS.items():
            for model_name, color in zip(group_info['models'], group_info['colors']):
                if model_name in pivot_df.index:
                    values = pivot_df.loc[model_name].tolist()
                    values += values[:1] # Close the circle
                    ax.plot(angles, values, linewidth=2, color=color, alpha=0.8, marker='o', markersize=4, zorder=5)
                    # Optional: ax.fill(angles, values, color=color, alpha=0.05) # Light fill

        # 4. Legend aesthetics (three-column)
        empty = Line2D([0], [0], color='none', label='')
        
        # Build legend columns
        col1 = [
            Line2D([0], [0], color="red", linestyle="--", label="Baseline (Clean)"),
            Line2D([0], [0], color='none', label=r'$\mathbf{CNN-based}$'),
            Line2D([0], [0], color='#1f77b4', linewidth=2, marker='o', label='  ResNet'),
            Line2D([0], [0], color='#00bfff', linewidth=2, marker='o', label='  EfficientNet'),
        ]
        col2 = [
            empty,
            Line2D([0], [0], color='none', label=r'$\mathbf{Transformers}$'),
            Line2D([0], [0], color='#ff7f0e', linewidth=2, marker='o', label='  ViT'),
            Line2D([0], [0], color='#d62728', linewidth=2, marker='o', label='  Swin-T'),
        ]
        col3 = [
            empty,
            Line2D([0], [0], color='none', label=r'$\mathbf{PFM}$'),
            Line2D([0], [0], color='#2ca02c', linewidth=2, marker='o', label='  GigaPath'),
            Line2D([0], [0], color='#9467bd', linewidth=2, marker='o', label='  UNI'),
            Line2D([0], [0], color='#8c564b', linewidth=2, marker='o', label='  Virchow2')
        ]
        
        ax.legend(handles=col1 + col2 + col3, loc='upper center', bbox_to_anchor=(0.5, -0.12), 
                  ncol=3, fontsize=9, frameon=True)

        # 5. Axis settings
        ax.set_theta_offset(np.pi / 2)
        ax.set_theta_direction(-1)
        ax.set_thetagrids(np.degrees(angles[:-1]), labels, fontsize=11, fontweight='bold')
        
        # Ticks
        ticks = np.arange(lower_limit, upper_limit + 5, 10)
        ax.set_ylim(lower_limit, upper_limit)
        plt.yticks(ticks, [f"{int(t)}%" for t in ticks], color="grey", size=9)

        plt.title(f"Model Robustness Profile: {dataset_name}", size=16, fontweight='bold', pad=30)
        plt.tight_layout()

        # Save
        save_path = os.path.join(output_dir, f"robustness_radar_{dataset_name.lower()}.png")
        plt.savefig(save_path, dpi=300, bbox_inches='tight')
        plt.close()

    print("Radar plots generated successfully!")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate radar plots for model robustness.")
    parser.add_argument("--input", type=str, required=True, help="Path to the evaluated CSV results.")
    parser.add_argument("--output-dir", type=str, default="./results/charts", help="Directory to save the charts.")
    
    args = parser.parse_args()
    main(args.input, args.output_dir)